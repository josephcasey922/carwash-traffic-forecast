"""WashCast Day-1 rollout audit: count accuracy, operational buckets, and lag-safe bias alerts.

Reads day1_hourly_residuals.csv generated by day1_event_diagnostics.py.
This is an evaluation and diagnostic script; it does NOT train a staffing classifier.
"""
from __future__ import annotations

import argparse
from pathlib import Path
import numpy as np
import pandas as pd

THRESHOLD_STARTS = np.array([18, 41, 61], dtype=float)
BUCKET_NAMES = ['0-17', '18-40', '41-60', '61+']


def bucket(washes: pd.Series | np.ndarray) -> np.ndarray:
    """Return current traffic bucket, with nonnegative fractional forecasts rounded half-up."""
    x = np.asarray(washes, dtype=float)
    counts = np.floor(np.maximum(x, 0) + 0.5)
    return np.searchsorted(THRESHOLD_STARTS, counts, side='right')


def load_residuals(path: Path) -> pd.DataFrame:
    d = pd.read_csv(path)
    required = {'location_id', 'local_date', 'hour', 'carwashes', 'prediction'}
    missing = required - set(d)
    if missing:
        raise ValueError(f'Missing required residual columns: {sorted(missing)}')
    if 'lead_day' in d:
        d = d[d['lead_day'] == 1].copy()
    d['local_date'] = pd.to_datetime(d['local_date'], errors='raise').dt.normalize()
    d['carwashes'] = pd.to_numeric(d['carwashes'], errors='raise')
    d['prediction'] = pd.to_numeric(d['prediction'], errors='raise')
    d = d.dropna(subset=['carwashes', 'prediction']).copy()
    if d.duplicated(['location_id', 'local_date', 'hour']).any():
        raise ValueError('Nonunique (location_id, local_date, hour); remove duplicate issuance records first')
    d['error'] = d['prediction'] - d['carwashes']
    d['absolute_error'] = d['error'].abs()
    d['actual_bucket'] = bucket(d['carwashes'])
    d['forecast_bucket'] = bucket(d['prediction'])
    d['bucket_error'] = d['forecast_bucket'] - d['actual_bucket']
    d['inferred_zero'] = d.get('inferred_zero', pd.Series(False, index=d.index)).fillna(False).astype(bool)
    return d.sort_values(['location_id', 'local_date', 'hour']).reset_index(drop=True)


def safe_pct(num: float, den: float) -> float:
    return 100 * num / den if den else float('nan')


def measurements(d: pd.DataFrame) -> dict:
    return dict(
        observations=len(d),
        mean_actual=float(d.carwashes.mean()),
        mae=float(d.absolute_error.mean()),
        median_ae=float(d.absolute_error.median()),
        wape_percent=safe_pct(d.absolute_error.sum(), d.carwashes.sum()),
        signed_bias=float(d.error.mean()),
        bucket_agreement_percent=safe_pct((d.bucket_error == 0).sum(), len(d)),
        bucket_under_percent=safe_pct((d.bucket_error < 0).sum(), len(d)),
        bucket_over_percent=safe_pct((d.bucket_error > 0).sum(), len(d)),
        multiple_bucket_misses=int((d.bucket_error.abs() > 1).sum()),
        observed_61plus=int((d.carwashes >= 61).sum()),
        predicted_61plus=int((d.forecast_bucket == 3).sum()),
    )


def store_scorecard(d: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for store, g in d.groupby('location_id'):
        hourly = measurements(g)
        days = g.groupby('local_date')['error'].mean()
        hi = g[g.carwashes >= 41]
        rows.append(dict(location_id=store, **hourly,
            days=int(days.size),
            days_underpredicted=int((days < 0).sum()),
            days_overpredicted=int((days > 0).sum()),
            actual_41plus_hours=int(len(hi)),
            recall_41plus_percent=safe_pct((hi.forecast_bucket >= 2).sum(), len(hi)),
            actual_61plus_hours=int((g.carwashes >= 61).sum()),
            recall_61plus_percent=safe_pct(((g.carwashes >= 61)&(g.forecast_bucket==3)).sum(), (g.carwashes >= 61).sum()),
        ))
    return pd.DataFrame(rows).sort_values('location_id')


def load_network_shocks(path: Path | None) -> set[pd.Timestamp]:
    """Flag *historically observed* exceptional network days for future monitoring inputs only."""
    if path is None:
        return set()
    n = pd.read_csv(path)
    required = {'local_date', 'fraction_stores_same_direction', 'network_bias_pct'}
    if not required.issubset(n):
        raise ValueError(f'Network file requires {sorted(required)}')
    shocked = n[(n.fraction_stores_same_direction >= .93) & (n.network_bias_pct.abs() >= 25)]
    return set(pd.to_datetime(shocked.local_date).dt.normalize())


def run_causal_monitor(d: pd.DataFrame, shock_dates: set[pd.Timestamp]) -> tuple[pd.DataFrame, pd.DataFrame]:
    """As-of target day D, use only completed dates <= D-2 (issued previous day ~6pm).

    Diagnostic policy, intentionally conservative and fixed (not hyperparameter-tuned):
    * Prior 21 calendar days, excluding yesterday (not complete by 6pm).
    * Require at least 10 eligible days, exclude suspect days with >=3 inferred zeros.
    * Exclude clearly extreme, fully synchronous network days from correction reference.
    * Declare persistent bias if >=70% of past days err same direction and
      magnitude >= max(1 wash/hr, 8% of rolling observed hourly mean).
    * Exploratory correction: -50% of median past bias, capped at +/-4 washes/hour.
    Outputs are diagnostic, NOT deployable coefficients. Do not tune on this holdout.
    """
    day = d.groupby(['location_id', 'local_date'], as_index=False).agg(
        mean_error=('error','mean'), actual_mean=('carwashes','mean'),
        inferred_zero_hours=('inferred_zero','sum'), hours=('hour','size'))
    day['shock'] = day.local_date.isin(shock_dates)
    flags = []
    adjustments = []
    for store,g in day.groupby('location_id',sort=True):
        g=g.sort_values('local_date').reset_index(drop=True)
        bydate = d[d.location_id == store].groupby('local_date', sort=False)
        for r in g.itertuples(index=False):
            target=r.local_date
            eligible=g[(g.local_date>=target-pd.Timedelta(days=22)) &
                       (g.local_date<=target-pd.Timedelta(days=2)) &
                       (g.inferred_zero_hours < 3) & (~g.shock)]
            n=len(eligible)
            prev_median=float(eligible.mean_error.median()) if n else float('nan')
            reference_volume=float(eligible.actual_mean.mean()) if n else float('nan')
            min_abs=max(1.0, .08*reference_volume) if n else float('nan')
            sign_frac = float((np.sign(eligible.mean_error)==np.sign(prev_median)).mean()) if n and prev_median != 0 else 0.0
            alert=bool(n>=10 and np.abs(prev_median)>=min_abs and sign_frac>=.70)
            adjustment=float(np.clip(-.5*prev_median, -4., 4.)) if alert else 0.0
            flags.append(dict(location_id=store, target_date=target.date(), history_days=n,
                historical_median_hourly_bias=prev_median,
                historical_sign_consistency=sign_frac, historical_avg_washes_per_hour=reference_volume,
                magnitude_threshold=min_abs, alert=alert,
                alert_direction=('underprediction' if alert and prev_median<0 else 'overprediction' if alert else 'none'),
                exploratory_offset=adjustment,
                current_actual_hourly_bias=float(r.mean_error)))
            for i, row in bydate.get_group(target).iterrows():
                adj_pred=max(0.,float(row.prediction)+adjustment)
                adjustments.append(dict(location_id=store,local_date=target.date(),hour=int(row.hour),
                    carwashes=float(row.carwashes),prediction=float(row.prediction),
                    corrected_prediction=adj_pred,absolute_error=float(row.absolute_error),
                    corrected_absolute_error=abs(adj_pred-float(row.carwashes)),
                    forecast_bucket=int(row.forecast_bucket),actual_bucket=int(row.actual_bucket),
                    corrected_bucket=int(bucket([adj_pred])[0]),offset=adjustment,
                    alert=alert))
    return pd.DataFrame(flags),pd.DataFrame(adjustments)


def write_report(residuals: Path, output: Path, network: Path | None = None) -> None:
    output.mkdir(parents=True, exist_ok=True)
    d=load_residuals(residuals)
    pd.DataFrame([measurements(d)]).to_csv(output/'rollout_summary.csv',index=False)
    store_scorecard(d).to_csv(output/'store_rollout_scorecard.csv', index=False)
    conf=pd.crosstab(pd.Series([BUCKET_NAMES[i] for i in d.actual_bucket],name='actual_washes'),
        pd.Series([BUCKET_NAMES[i] for i in d.forecast_bucket],name='predicted_washes'),
        dropna=False).reindex(index=BUCKET_NAMES,columns=BUCKET_NAMES,fill_value=0)
    conf.to_csv(output/'bucket_confusion_counts.csv')
    breakdown=[]
    for name,mask in [('all',pd.Series(True,index=d.index)),
                      ('not_inferred_zero_hour',~d.inferred_zero),
                      ('outside_extreme_synchronous_days',~d.local_date.isin(load_network_shocks(network))),
                      ('neither',(~d.inferred_zero)&(~d.local_date.isin(load_network_shocks(network))))]:
        breakdown.append(dict(segment=name,**measurements(d[mask])))
    pd.DataFrame(breakdown).to_csv(output/'sensitivity.csv',index=False)
    flags, adj = run_causal_monitor(d, load_network_shocks(network))
    flags.to_csv(output/'lag_safe_persistent_bias_alerts.csv',index=False)
    online=[]
    for name,g in [('network',adj), *list(adj.groupby('location_id'))]:
        online.append(dict(location_id=name,observations=len(g),
            initial_mae=g.absolute_error.mean(), exploratory_corrected_mae=g.corrected_absolute_error.mean(),
            initial_bucket_agreement_percent=100*(g.forecast_bucket==g.actual_bucket).mean(),
            exploratory_bucket_agreement_percent=100*(g.corrected_bucket==g.actual_bucket).mean(),
            alert_hours=int(g.alert.sum()),
            initial_bias=(g.prediction-g.carwashes).mean(),
            exploratory_bias=(g.corrected_prediction-g.carwashes).mean()))
    pd.DataFrame(online).to_csv(output/'exploratory_online_correction.csv',index=False)
    print(f'Wrote rollout audit to: {output.resolve()}')
    print(pd.DataFrame([measurements(d)]).to_string(index=False))
    print(pd.DataFrame(online).head(1).to_string(index=False))


def cli() -> None:
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--residuals',required=True,type=Path)
    ap.add_argument('--network',type=Path, help='Optional network_synchronous_days.csv')
    ap.add_argument('--output',default=Path('rollout_audit'),type=Path)
    a=ap.parse_args()
    write_report(a.residuals,a.output,a.network)

if __name__=='__main__':
    cli()
